@pytest.mark.parametrize("rule,text", HOSTILE, ids=[f"{r}-{i}" for i, (r, _) in enumerate(HOSTILE)])
def test_hostile_markdown_is_flagged(rule: str, text: str) -> None:
    assert rule in rules("# t\n\n" + text + "\n"), check_markdown(text, DOC)


def test_inert_contexts_are_not_checked() -> None:
    text = "```\n<script>x</script>\n[a](javascript:1)\n![i](https://evil.example/p.png)\n```\n\n`<iframe>` and `[a](javascript:1)`\n"
    assert check_markdown(text, DOC) == []


def test_a_fence_must_close_with_a_matching_fence() -> None:
    # ```` opens a four-backtick fence; a three-backtick line inside does not close it
    text = "````\n```\n<script>x</script>\n````\n\n<script>y</script>\n"
    found = check_markdown(text, DOC)
    assert [f.line for f in found if f.rule == "html-tag"] == [6]


def test_oversize_document() -> None:
    assert rules("a" * (2 * 1024 * 1024 + 1)) == {"too-large"}


def test_findings_carry_path_and_line() -> None:
    f = check_markdown("ok\n\n[x](javascript:1)\n", DOC)[0]
    assert (f.path, f.line) == (DOC, 3)


@pytest.mark.parametrize("url,image,expected", [
    ("#section", False, None),
    ("page.md", False, None),
    ("https://example.com", False, None),
    ("diagrams/a.svg", True, None),
    ("../img/a.png", True, "image-outside-docs"),
    ("a.svg", True, None),
    ("https://example.com/a.svg", True, "image-remote"),
])
def test_check_url(url: str, image: bool, expected: str | None) -> None:
    assert check_url(url, image=image, doc_path="docs/guide.md") == expected
