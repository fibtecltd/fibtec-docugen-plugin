from __future__ import annotations

import pytest

from docugen.verify.md_policy import check_markdown, check_url

DOC = "docs/guide/intro.md"


def rules(text: str, path: str = DOC) -> set[str]:
    return {f.rule for f in check_markdown(text, path)}


CLEAN = """\
# Title

Text with a [relative link](../api.md#routes), a [source link](../../src/app.py),
an [https link](https://example.com/page?x=1&y=2), an <https://example.com> autolink and
a diagram:

![class diagram](diagrams/classes.svg)

Line break<br>and <details><summary>more</summary>hidden</details> with `code <script>` inline.

```html
<script>alert(1)</script>
[x](javascript:alert(1))
```

~~~
<iframe src="https://evil.example"></iframe>
~~~

<!-- generated by docugen -->
| a | b |
|---|---|
| 1 | 2 |
"""


def test_clean_document_passes() -> None:
    assert check_markdown(CLEAN, DOC) == []


